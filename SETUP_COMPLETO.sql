on public.contactos for select
to authenticated
using (public.es_administrador());

create policy "admin_actualiza_contactos"
on public.contactos for update
to authenticated
using (public.es_administrador())
with check (public.es_administrador());

create policy "admin_elimina_contactos"
on public.contactos for delete
to authenticated
using (public.es_administrador());

create policy "web_publica_lee_proyectos"
on public.proyectos for select
to anon, authenticated
using (publicado = true or public.es_administrador());

create policy "admin_lee_proyectos"
on public.proyectos for select
to authenticated
using (public.es_administrador());

create policy "admin_inserta_proyectos"
on public.proyectos for insert
to authenticated
with check (public.es_administrador());

create policy "admin_actualiza_proyectos"
on public.proyectos for update
to authenticated
using (public.es_administrador())
with check (public.es_administrador());

create policy "admin_elimina_proyectos"
on public.proyectos for delete
to authenticated
using (public.es_administrador());

create policy "web_publica_lee_imagenes"
on public.proyecto_imagenes for select
to anon, authenticated
using (
  exists (
    select 1 from public.proyectos p
    where p.id = proyecto_id
      and (p.publicado = true or public.es_administrador())
  )
);

create policy "admin_lee_imagenes"
on public.proyecto_imagenes for select
to authenticated
using (public.es_administrador());

create policy "admin_inserta_imagenes"
