create table if not exists public.contactos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nombre text not null,
  empresa text,
  correo text not null,
  telefono text,
  servicio text,
  mensaje text not null,
  estatus text not null default 'Nuevo'
);

create table if not exists public.proyectos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  titulo text not null,
  descripcion text,
  imagen_url text,
  tipo text default 'Proyecto',
  publicado boolean not null default true
);

create table if not exists public.proyecto_imagenes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  proyecto_id bigint not null references public.proyectos(id) on delete cascade,
  imagen_url text not null,
  orden integer default 0
);

-- Guarda los usuarios de Supabase Auth autorizados para /admin.
create table if not exists public.administradores (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.contactos enable row level security;
alter table public.proyectos enable row level security;
alter table public.proyecto_imagenes enable row level security;
alter table public.administradores enable row level security;

-- Función segura para verificar si la sesión pertenece a un administrador.
create or replace function public.es_administrador()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.administradores
    where user_id = auth.uid()
  );
$$;

revoke all on function public.es_administrador() from public;
grant execute on function public.es_administrador() to anon, authenticated;

